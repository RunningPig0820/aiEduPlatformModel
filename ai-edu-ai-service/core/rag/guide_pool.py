# 未知模块/缺省兜底（防御, 正常前端必传 current_project）
FALLBACK_MODULE = "ai-tutoring"

# 主方向闭集（rag 组是子集, 不占主方向）
DIRECTIONS = ("intro", "operation", "data_relation", "difficulty")


def pool_for(module: str | None) -> dict:
    """模块池；未知/缺省 → FALLBACK_MODULE 兜底。"""
    return GUIDE_POOL.get(module or "", GUIDE_POOL[FALLBACK_MODULE])


def scope_questions(module: str | None, directions: tuple = ()) -> list:
    """池内全部问题去重保序；directions 非空时限定方向（rag 组与其他组重复, 去重）。"""
    pool = pool_for(module)
    dirs = directions or DIRECTIONS
    out, seen = [], set()
    for d in dirs:
        for q in pool.get(d, []):
            if q not in seen:
                seen.add(q)
                out.append(q)
    return out


# 入口引导通用模板(所有模块共用, 避免每模块写死; {模块} = 模块中文名占位, 动态替换)
# 注意: 模板用"这个功能"而非"这个系统/这个项目"——入口引导是给使用方看的,
#       AI答疑是"功能", "系统/项目"是开发/面试视角的词(2026-08-26 用户反馈)。
# 2026-08-26 删 rag 入口题"这个功能的底层是怎么实现的?"——太泛, "底层"同时匹配
# 架构/ActionMeta/召回等一堆块, 没有明确答案, 检索答非所问; 入口只保留可答的具体功能题。
_ENTRY_TEMPLATES = (
    ("intro", "能不能先介绍一下{模块}？"),
    ("intro", "{模块}是干什么的？"),
    ("intro", "这个功能解决了什么问题？"),
    ("operation", "这个功能是怎么用的？"),
)

# 模块 id → 中文名(entry 模板替换用; 与 assistant.MODULE_ZH 同闭集)
_MODULE_ZH = {
    "ai-tutoring": "AI答疑",
    "knowledge-graph": "知识图谱",
    "question-analysis": "题型分析",
    "rag-system": "RAG项目",
}


def entry_for(module: str | None) -> list:
    """入口引导（入门级, 带 direction）: 通用模板 + 模块中文名动态替换。

    所有模块共用模板, 引导语跟着模块名走——**不写死某个模块名**（用户还不知道
    怎么用, 先给"X 是干什么的"级别简单题; 难题留给结束建议）。每模块可覆盖:
    entry 组存在则优先（用于定制入口重点）。返回 [(direction, 问题), ...]。
    """
    pool = pool_for(module)
    entry = pool.get("entry")
    if entry:
        return entry
    name = _MODULE_ZH.get(module or "", _MODULE_ZH[FALLBACK_MODULE])
    return [(d, tpl.format(模块=name)) for d, tpl in _ENTRY_TEMPLATES]
