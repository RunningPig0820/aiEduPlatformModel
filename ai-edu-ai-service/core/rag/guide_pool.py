# 未知模块/缺省兜底（防御, 正常前端必传 current_project）
FALLBACK_MODULE = "ai-tutoring"

# 主方向闭集（rag 组是子集, 不占主方向）
DIRECTIONS = ("intro", "operation", "data_relation", "difficulty")


def pool_for(module: str | None) -> dict:
    """模块池；未知/缺省 → FALLBACK_MODULE 兜底。"""
    return GUIDE_POOL.get(module or "", GUIDE_POOL[FALLBACK_MODULE])


def scope_questions(module: str | None, directions: tuple = ()) -> list:
    """池内全部问题去重保序；directions 非空时限定方向（rag 组与其他组重复, 去重）。"""
    pool = pool_for(module)
    dirs = directions or DIRECTIONS
    out, seen = [], set()
    for d in dirs:
        for q in pool.get(d, []):
            if q not in seen:
                seen.add(q)
                out.append(q)
    return out


# 入口引导通用模板(所有模块共用, 避免每模块写死; {模块} = 模块中文名占位, 动态替换)
# 注意: 模板用"这个功能"而非"这个系统/这个项目"——入口引导是给使用方看的,
#       AI答疑是"功能", "系统/项目"是开发/面试视角的词(2026-08-26 用户反馈)。
